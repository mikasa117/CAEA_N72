void es8389_set_adc_mute(bool mute)
{
    uint8_t regv;
    regmap_read(g_es8389_addr, ES8389_ADC_SP_CONTROL_REG0x20, &regv);
    regv &= 0xFC;
    if (mute)
    {
        regv |= 0x03;
    }
    regmap_write(g_es8389_addr, ES8389_ADC_SP_CONTROL_REG0x20, regv);
}

void es8389_set_dac_mute(bool mute)
{

    uint8_t regv;
    regmap_read(g_es8389_addr, ES8389_DAC_CONTROL_REG0x40, &regv);
    regv &= 0xFC;
    if (mute)
    {
        regv |= 0x03;
    }
    regmap_write(g_es8389_addr, ES8389_DAC_CONTROL_REG0x40, regv);
}

/**
 * @brief 配置mic的增益
 *
 * @param gain_db
 */
static void es8389_set_mic_gain(es8389_mic_gain_t gain_db)
{

    // 左声道
    regmap_write(g_es8389_addr, ES8389_PGA1_GAIN_CONTROL_REG0x72, gain_db | (1 << 4));
    // 右声道
    regmap_write(g_es8389_addr, ES8389_PGA1_GAIN_CONTROL_REG0x73, gain_db | (1 << 4));
}

